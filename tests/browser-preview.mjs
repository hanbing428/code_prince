import path from 'node:path'
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'

// 在浏览器适配器中操作真实 Vue 页面，平台原生能力仍需微信端单独验收。
const require = createRequire(import.meta.url)
const { chromium } = require(process.argv[2] || 'playwright')
const root = fileURLToPath(new URL('../', import.meta.url))
const evidence = path.join(root, 'docs/evidence')
fs.mkdirSync(evidence, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.argv[3] || chromium.executablePath() })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const visible = text => page.getByText(text, { exact: true }).waitFor()
const click = name => page.getByRole('button', { name, exact: true }).click()
try {
	await page.goto('http://127.0.0.1:4175/')
	await visible('小满的纪念馆')
	await page.screenshot({ path: path.join(evidence, 'home-preview.png'), fullPage: true })
	await page.getByText('小满的纪念馆', { exact: true }).click()
	await visible('关于 小满')
	await page.screenshot({ path: path.join(evidence, 'memorial-preview.png'), fullPage: true })
	await page.evaluate(() => uni.switchTab({ url: '/pages/mine/index' }))
	await click('模拟登录 · 宠物主人')
	await visible('小满的家人')
	await click('＋ 新建')
	await page.getByPlaceholder('那个你叫过无数次的名字').fill('团团')
	await page.getByPlaceholder('从第一次相遇，或者一个难忘的小习惯开始……').fill('我们一起走过很多有阳光的日子。')
	await click('创建纪念馆')
	await visible('关于 团团')
	await visible('仅自己可见')
	await click('＋ 写回忆')
	await page.getByPlaceholder('比如：第一次一起看海').fill('一起看海的那天')
	await page.getByPlaceholder('它那时是什么模样？你们做了什么？').fill('你追着浪花，我们笑了一整个下午。')
	const chooser = page.waitForEvent('filechooser')
	await click('＋ 添加一张照片')
	await (await chooser).setFiles(path.join(root, 'static/logo.png'))
	await visible('换一张照片')
	await click('珍藏这段回忆')
	await visible('一起看海的那天')
	await page.getByRole('button', { name: /献一束花/ }).click()
	await visible('已经收到 1 份温柔的惦念')
	await page.getByRole('button', { name: /点一盏灯/ }).click()
	await visible('已经收到 2 份温柔的惦念')
	await page.getByPlaceholder('愿你在另一个世界，也被温柔以待。').fill('今天也很想你。')
	await click('留下思念')
	await visible('今天也很想你。')
	await click('整理纪念馆')
	await click('公开 · 可以分享')
	await click('保存这份纪念')
	await click('确定')
	await visible('公开纪念馆')
	const sharedRoute = new URL(page.url()).hash.slice(1)
	await page.screenshot({ path: path.join(evidence, 'created-memorial-preview.png'), fullPage: true })
	await page.evaluate(() => uni.switchTab({ url: '/pages/mine/index' }))
	await click('退出登录')
	await click('模拟登录 · 来访亲友')
	await page.evaluate(url => uni.navigateTo({ url }), sharedRoute)
	await visible('关于 团团')
	assert.equal(await page.getByRole('button', { name: '整理纪念馆', exact: true }).count(), 0)
	await page.getByPlaceholder('愿你在另一个世界，也被温柔以待。').fill('愿你安好。')
	await click('留下思念')
	await visible('愿你安好。')
	await click('举报纪念馆')
	await click('不适当的内容')
	await visible('已记录举报')
	await page.evaluate(() => uni.switchTab({ url: '/pages/mine/index' }))
	await click('切换到管理演示')
	await click('进入内容管理演示')
	await visible('不适当的内容')
	await click('下架对应内容')
	await click('确定')
	await visible('已处理')
	await page.waitForFunction(() => !document.querySelector('.toast'))
	await page.screenshot({ path: path.join(evidence, 'admin-preview.png'), fullPage: true })
	assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, '页面不应横向溢出')
	assert.deepEqual(errors, [], '浏览器不应出现运行时错误')
	console.log('PASS 浏览器适配预览：访客浏览、登录、私密建馆、图片回忆、祭奠、留言、公开设置、亲友权限、举报与管理下架；无运行时错误')
} catch (error) {
	await page.screenshot({ path: path.join(evidence, 'browser-failure.png'), fullPage: true })
	console.error('浏览器错误：', errors)
	throw error
} finally { await browser.close() }
